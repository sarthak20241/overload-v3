/**
 * Marks portrait screen support as optional in the Android manifest.
 *
 * app.json sets "orientation": "portrait", so the main activity gets
 * screenOrientation="portrait". Android then implies
 * <uses-feature android.hardware.screen.portrait required="true">, and Google
 * Play hides the app from devices that do not report that feature (some
 * tablets, Chromebooks, Android XR). Play Console flags it as "Required
 * hardware feature declarations are restricting your app's availability".
 *
 * Declaring the feature with required="false" lifts that filter. The app still
 * shows in portrait only: screenOrientation is unchanged.
 *
 * android/ is gitignored and regenerated by `expo prebuild`, so the line has to
 * come from this plugin, not from a hand edit of AndroidManifest.xml.
 */
const { withAndroidManifest } = require('expo/config-plugins');

const FEATURE = 'android.hardware.screen.portrait';

function withOptionalPortrait(config) {
  return withAndroidManifest(config, (cfg) => {
    const manifest = cfg.modResults.manifest;
    const features = (manifest['uses-feature'] ??= []);
    const existing = features.find((f) => f.$?.['android:name'] === FEATURE);
    if (existing) {
      existing.$['android:required'] = 'false';
    } else {
      features.push({ $: { 'android:name': FEATURE, 'android:required': 'false' } });
    }
    return cfg;
  });
}

module.exports = withOptionalPortrait;
