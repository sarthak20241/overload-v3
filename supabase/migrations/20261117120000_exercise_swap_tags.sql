-- Swap tags on the exercise catalog: which exercises can stand in for which.
--
-- Two exercises are a like-for-like swap when they train the same muscle with
-- the same kind of movement. Neither existing column says that:
--
--   muscle_group      is the group the user sees and edits. It is often the
--                     parent ("Chest") where the swap needs the head ("Upper
--                     Chest"), and 371 rows say "Other".
--   movement_pattern  belongs to the form checker (0101). It has 9 families,
--                     was filled by a name regex ("Bench Jump" is a
--                     horizontal_press there), and "none" means "a camera
--                     cannot judge this", not "no movement".
--
-- So two new columns, and neither existing one is touched:
--
--   target_muscle  the exact muscle the exercise is picked for, in the app's
--                  own muscle words (lib/exercises ALL_MUSCLE_GROUPS). Free
--                  text like muscle_group, so a new head needs no migration.
--   swap_pattern   the movement family, from SWAP_PATTERN_VALUES in
--                  supabase/functions/_shared/exerciseVocab.ts (a test keeps
--                  this file and that list in step).
--
-- NULL means not tagged yet: a reader falls back to muscle_group.
--
-- The tags below are keyed by name_lower and cover every catalog name. A
-- user's own exercise with a catalog name gets the same tags. Names that only
-- users have are tagged outside this file, so no user's text is in the repo.

alter table public.exercises add column if not exists target_muscle text;
alter table public.exercises add column if not exists swap_pattern text;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'exercises_swap_pattern_check') then
    alter table public.exercises add constraint exercises_swap_pattern_check
      check (swap_pattern is null or swap_pattern in (
        'horizontal_press', 'vertical_press', 'dip', 'fly', 'vertical_pull', 'horizontal_pull',
        'pullover', 'shrug', 'upright_row', 'reverse_fly', 'raise', 'curl',
        'elbow_extension', 'wrist', 'hold', 'carry', 'squat', 'lunge',
        'hinge', 'hip_thrust', 'back_extension', 'leg_extension', 'leg_curl', 'hip_abduction',
        'hip_adduction', 'hip_kickback', 'calf_raise', 'crunch', 'leg_raise', 'rotation',
        'plank', 'rollout', 'neck', 'olympic', 'jump', 'throw',
        'cardio', 'mobility', 'other'));
  end if;
end $$;

comment on column public.exercises.target_muscle is
  'The exact muscle this exercise is picked for (app muscle words, head level '
  'where one applies). Used to rank swaps. NULL = not tagged, read muscle_group.';
comment on column public.exercises.swap_pattern is
  'Movement family for swaps (SWAP_PATTERN_VALUES in _shared/exerciseVocab.ts). '
  'Not the form checker''s movement_pattern. NULL = not tagged.';

-- The swap list reads "same muscle, then same movement" over the catalog.
create index if not exists idx_exercises_swap
  on public.exercises (target_muscle, swap_pattern);

